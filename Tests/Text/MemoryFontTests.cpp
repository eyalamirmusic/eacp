constexpr auto testFamily = "EacpTestSans";
constexpr auto testPostScriptName = "EacpTestSans-Regular";

bool approx(float a, float b, float tolerance = 1.f)
{
    return a > b - tolerance && a < b + tolerance;
}

FontRequest requestFor(const std::string& name)
{
    auto request = FontRequest {};
    request.family = name;
    request.pointSize = 100.f;
    request.scale = 1.f;

    return request;
}
