auto tRegisteringReportsTheNames =
    test("MemoryFont/registeringReportsTheNamesThePlatformFilesTheFaceUnder") = []
{
    const auto registered = registerMemoryFont(testFont, sizeof(testFont));

    check(registered.has_value(), "the font registers");

    if (!registered)
        return;

    check(registered->family == testFamily);
    check(registered->postScriptName == testPostScriptName);
};

auto tBothNamesResolveToTheFace =
    test("MemoryFont/aRegisteredFaceResolvesByItsFamilyAndByItsPostScriptName") = []
{
    const auto registered = registerMemoryFont(testFont, sizeof(testFont));

    if (!registered)
        return;

    const auto byFamily = GlyphRasterizer {requestFor(registered->family)};
    check(byFamily.isValid());
    check(byFamily.resolvedFamily() == registered->family);

    const auto byPostScriptName = GlyphRasterizer {requestFor(registered->postScriptName)};
    check(byPostScriptName.isValid());
    check(byPostScriptName.resolvedFamily() == registered->family);
};

auto tTheFaceShapes = test("MemoryFont/aRegisteredFaceShapesWithItsOwnAdvances") = []
{
    const auto registered = registerMemoryFont(testFont, sizeof(testFont));

    if (!registered)
        return;

    const auto rasterizer = GlyphRasterizer {requestFor(registered->family)};
    const auto run = rasterizer.shape("A", {});

    // 'A' advances 600 of 1000 units, so 60 pixels at a 100-pixel em; the
    // space 300.
    check(run.glyphs.size() == 1);
    check(approx(run.advance, 60.f));
    check(approx(rasterizer.shape(" ", {}).advance, 30.f));

    const auto metrics = rasterizer.metrics(FontVariant {});
    check(approx(metrics.ascent, 80.f));
    check(approx(metrics.descent, 20.f));
};

auto tRegisteringAgainIsNotAnError =
    test("MemoryFont/registeringTheSameFaceAgainReportsItAsItWas") = []
{
    const auto first = registerMemoryFont(testFont, sizeof(testFont));
    const auto second = registerMemoryFont(testFont, sizeof(testFont));

    check(first.has_value() && second.has_value());

    if (first && second)
    {
        check(first->family == second->family);
        check(first->postScriptName == second->postScriptName);
    }
};

auto tNotAFontRegistersNothing = test("MemoryFont/bytesThatAreNotAFontRegisterNothing") = []
{
    constexpr char junk[] = "not a font at all";

    check(!registerMemoryFont(junk, sizeof(junk)).has_value());
    check(!registerMemoryFont(nullptr, 0).has_value());
    check(!registerMemoryFont(testFont, 0).has_value());
};
