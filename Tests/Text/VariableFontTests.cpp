// A variable face's weights, against a face no machine has installed: the
// three-glyph TrueType MemoryFontTests registers, built here from three
// masters into one file with a wght axis running 200 to 900 and its default
// at 400, along which 'A' widens from 400 units of its 1000-unit em to 1000.
// The weight therefore shows in an advance, and no glyph has to be rasterized
// to see it. Neither end of the axis is 400 or 700, so the face's default
// instance and whatever bold the platform can synthesize from it are both
// distinguishable from the weight actually asked for.
//
// A variable face is the one case matching a face cannot answer. The platform
// files one file under one family, so the family has no lighter or bolder
// sibling to match a weight against, and the weight has to be asked of the
// axis instead. Until it was, a page declaring `@font-face { font-weight: 100
// 900 }` drew every weight in that range as the default instance or as the
// synthesized bold - Inter's nine weights came out as two.

